"""Opt-in browser integration with REAL installed checkpoints, synthetic reference only."""
import os
import time
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
url=os.getenv('STUDIO2_TEST_URL','http://127.0.0.1:8772')
reference=Path(os.environ['STUDIO2_TEST_REFERENCE'])
name='REAL Browser AI Fixture '+str(int(time.time()))
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--autoplay-policy=no-user-gesture-required'])
    page=browser.new_page(viewport={'width':1440,'height':1000},accept_downloads=True)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(url)
    page.get_by_role('button',name='Add Family Member').click()
    page.locator('#name').fill(name)
    page.locator('#authorization').fill('Synthetic fixture generated by official licensed checkpoints. Not a family member. Automated validation only.')
    page.locator('#consent').check();page.get_by_role('button',name='Save Profile',exact=True).click()
    card=page.locator('article.card').filter(has=page.get_by_role('heading',name=name,exact=True));card.wait_for()
    card.get_by_role('button',name='Add Recording',exact=True).click()
    page.locator('#audio-file').set_input_files(reference)
    expect(page.locator('#save-record')).to_be_enabled(timeout=30000)
    page.get_by_role('button',name='Save Reference',exact=True).click()
    card.get_by_role('button',name='Select Voice',exact=True).click()
    page.locator('#script').fill('This is a real browser synthesis test.')
    page.get_by_role('button',name='Generate Speech',exact=True).click()
    expect(page.locator('#history audio')).to_have_count(1,timeout=300000)
    player=page.locator('#history audio').first
    player.evaluate('(a)=>a.play()');page.wait_for_timeout(1000)
    assert player.evaluate('(a)=>a.currentTime')>0
    player.evaluate('(a)=>a.pause()')
    for format in ('WAV','MP3'):
        with page.expect_download() as download:
            page.get_by_role('link',name='Export '+format,exact=True).first.click()
        assert Path(download.value.path()).stat().st_size>1000
        assert download.value.suggested_filename.startswith('AI-generated-')
    print('PASS: REAL browser AI generation, history, actual playback and WAV/MP3 downloads',flush=True)
    page.locator('#script').fill('First script.\n\nSecond script.')
    page.get_by_role('button',name='Batch · Blank-line-separated scripts',exact=True).click()
    expect(page.locator('#history audio')).to_have_count(3,timeout=300000)
    print('PASS: REAL batch speech from two browser scripts',flush=True)
    page.locator('#convert-file').set_input_files(reference)
    page.get_by_role('button',name='Convert Recording',exact=True).click()
    expect(page.locator('#history audio')).to_have_count(4,timeout=300000)
    print('PASS: REAL browser recorded voice conversion and saved history',flush=True)
    page.get_by_role('button',name='Storage & Privacy',exact=True).click()
    with page.expect_download() as download:
        page.get_by_role('link',name='Export Private Backup',exact=True).click()
    assert Path(download.value.path()).stat().st_size>1000
    page.get_by_role('button',name='Family Voice Library',exact=True).click()
    page.screenshot(path='/workspace/voice-cloner/Studio-2.0/.runtime/real-browser-dashboard.png',full_page=True)
    page.on('dialog',lambda d:d.accept())
    card.get_by_role('button',name='Delete Profile',exact=True).click()
    card.wait_for(state='detached')
    assert not errors,errors
    print('PASS: private browser backup, synthetic fixture deletion; no JavaScript errors',flush=True)
    browser.close()
