from playwright.sync_api import sync_playwright, expect
import time
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--autoplay-policy=no-user-gesture-required'])
 page=b.new_page(permissions=['microphone'],viewport={'width':1440,'height':1000})
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8770')
 page.get_by_text('0 profiles',exact=True).wait_for()
 page.get_by_role('button',name='Add Family Member').click()
 page.locator('#name').fill('Browser Family Test')
 page.locator('#authorization').fill('Adult written permission for synthetic browser test.')
 page.locator('#consent').check()
 page.get_by_role('button',name='Save Profile',exact=True).click()
 card=page.locator('article.card').filter(has=page.get_by_role('heading',name='Browser Family Test',exact=True))
 card.wait_for()
 card.get_by_role('button',name='Add Recording').click()
 page.get_by_role('button',name='Enable Microphone').click()
 page.get_by_role('button',name='Record',exact=True).wait_for()
 expect(page.locator("#start-record")).to_be_enabled()
 page.get_by_role('button',name='Record',exact=True).click()
 page.wait_for_timeout(4000)
 page.get_by_role('button',name='Stop',exact=True).click()
 expect(page.locator("#save-record")).to_be_enabled()
 page.get_by_role('button',name='Save Reference',exact=True).click()
 page.get_by_text('English · 1 recordings',exact=True).wait_for()
 card.get_by_role('button',name='Play Voice Sample').click()
 page.wait_for_timeout(1000)
 assert card.locator("audio").evaluate("a => a.currentTime") > 0
 card.get_by_role('button',name='Select Voice',exact=True).click()
 page.get_by_role('heading',name='Browser Family Test’s workspace').wait_for()
 assert page.locator('#voice-select').input_value()
 page.get_by_role('button',name='Family Voice Library',exact=True).click()
 page.screenshot(path='/workspace/ai-voice-cloning-studio-2/dashboard.png',full_page=True)
 page.on('dialog',lambda dialog:dialog.accept())
 card.get_by_role('button',name='Revoke Consent',exact=True).click()
 page.get_by_text('Consent revoked',exact=True).wait_for()
 assert card.get_by_role('button',name='Play Voice Sample').is_disabled()
 card.get_by_role('button',name='Delete Profile',exact=True).click()
 page.get_by_text('0 profiles',exact=True).wait_for()
 assert not errors,errors
 print('PASS: profile create, synthetic microphone recording, evaluation/save, playback, selection, consent revocation, deletion; no JavaScript errors')
 b.close()
